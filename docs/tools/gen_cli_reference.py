#!/usr/bin/env python3
"""Generate docs/reference/cli-commands.md from the installed pygeofetch CLI.

Run from the repository root:

    python docs/tools/gen_cli_reference.py > docs/reference/cli-commands.md

The page is derived from the live Click command tree, so it cannot drift from
the code. ``docs/tools/check_docs.py`` fails CI if the committed page is stale.
"""
from __future__ import annotations

import sys
import textwrap

import click

from pygeofetch.cli.main import cli

# Display order and one-line purpose for each top-level group.
GROUPS = [
    ("auth", "Manage provider credentials."),
    ("providers", "Browse and inspect the provider registry."),
    ("search", "Federated search across providers."),
    ("download", "Download scenes and inspect download history."),
    ("cache", "Manage the search-result cache."),
    ("pipeline", "YAML acquisition pipelines: run, validate and schedule."),
    ("proc-pipeline", "YAML processing-chain pipelines for files you already have."),
    ("preprocess", "Clip, reproject, mask, correct and mosaic rasters."),
    ("index", "Spectral indices and band arithmetic."),
    ("classify", "Unsupervised and supervised classification."),
    ("post", "Vector and raster post-processing."),
    ("sar", "SAR despeckling, calibration, flood mapping and coherence."),
    ("optical", "Optical pixel-offset tracking."),
    ("multisensor", "Multi-sensor pipelines."),
    ("stream", "Windowed COG reads and cloud-native format conversion."),
    ("config", "Read and modify configuration."),
]
TOP_LEVEL_LEAVES = [
    "status", "doctor", "version", "geocode", "reverse-geocode",
    "assess-feasibility", "--install-completion",
]


def esc(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def usage(cmd: click.Command, path: list[str]) -> str:
    ctx = click.Context(cmd, info_name=path[-1])
    pieces = cmd.collect_usage_pieces(ctx)
    return " ".join(["pygeofetch", *path[:-1], path[-1], *pieces]).strip()


def option_rows(cmd: click.Command) -> tuple[list[str], list[str]]:
    args, opts = [], []
    for p in cmd.params:
        if isinstance(p, click.Argument):
            kind = "required" if p.required else "optional"
            args.append(f"| `{p.name.upper()}` | {kind} |")
        elif isinstance(p, click.Option):
            names = ", ".join(f"`{n}`" for n in [*p.opts, *p.secondary_opts])
            default = ""
            if p.show_default or (p.default not in (None, False, ()) and not p.is_flag):
                d = p.default
                if d is not None and "UNSET" not in repr(d):
                    default = f"`{d}`"
            if p.required:
                default = "required"
            if p.is_flag:
                ptype = "flag"
            elif isinstance(p.type, click.Choice):
                ptype = "one of: " + ", ".join(p.type.choices)
            else:
                ptype = getattr(p.type, "name", None) or str(p.type).lower()
            opts.append(f"| {names} | {esc(ptype)} | {default} | {esc(p.help or '')} |")
    return args, opts


def emit(cmd: click.Command, path: list[str], level: int, out: list[str]) -> None:
    out.append(f"{'#' * level} `{' '.join(path)}`\n")
    doc = textwrap.dedent((cmd.help or "").replace("\x08", "")).strip()
    if doc:
        head, _, rest = doc.partition("\n\n")
        out.append(head.replace("\n", " ") + "\n")
        if rest.strip():
            out.append("```text\n" + textwrap.dedent(rest).strip() + "\n```\n")
    out.append("```text\n" + usage(cmd, ["pygeofetch", *path][1:]) + "\n```\n")
    args, opts = option_rows(cmd)
    if args:
        out.append("| Argument | |\n|---|---|\n" + "\n".join(args) + "\n")
    if opts:
        out.append(
            "| Option | Type | Default | Description |\n|---|---|---|---|\n"
            + "\n".join(opts)
            + "\n"
        )


def main() -> None:
    out: list[str] = [
        "<!-- GENERATED by docs/tools/gen_cli_reference.py. Do not edit by hand. -->\n",
        "# Command reference\n",
        "Every command and option in the installed CLI. For worked examples see "
        "[Command-line guide](cli.md).\n",
        "```{contents}\n:local:\n:depth: 1\n```\n",
    ]
    for name, blurb in GROUPS:
        group = cli.commands[name]
        out.append(f"## `{name}`\n")
        out.append(blurb + "\n")
        subs = list(group.commands.items()) if isinstance(group, click.Group) else []
        if subs:
            out.append("| Command | Purpose |\n|---|---|")
            for sub, c in subs:
                first = (c.help or "").strip().split("\n")[0]
                out.append(f"| [`{name} {sub}`](#{name}-{sub}) | {esc(first)} |")
            out.append("")
            for sub, c in subs:
                emit(c, [name, sub], 3, out)
        else:
            emit(group, [name], 3, out)
    out.append("## Top-level commands\n")
    for name in TOP_LEVEL_LEAVES:
        emit(cli.commands[name], [name], 3, out)
    covered = {n for n, _ in GROUPS} | set(TOP_LEVEL_LEAVES)
    missing = set(cli.commands) - covered
    if missing:
        sys.stderr.write(f"WARNING: command groups not in the reference: {sorted(missing)}\n")
    sys.stdout.write("\n".join(out).rstrip() + "\n")


if __name__ == "__main__":
    main()
